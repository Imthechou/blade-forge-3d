/**
 * 数据层 · S8 刀柄配色（第一方覆盖表）
 *
 * 定位：**基线是原项目的取值**（`handleMaterials.js` / `cardWrites.js` 的 legacy 表），
 *   本表只做两类**有实测依据**的小改，不做整体重配色
 *   （2026-10-16：上一版整体重配色被判定"不如原项目"，已撤回）。
 *
 * ── 改动一：去掉"奇怪的红色底" ─────────────────────────────────────
 * 实测（tools/probe-handle-hue.mjs，刀柄掩码内按色相统计）：
 *   木质/皮胶 4 张的**渲染色相全部落在红区**，且"有色像素里 100% 是红"：
 *     S8_01 温木柄 tint #87562f → 渲染 19.3°
 *     S8_02 握皮纹      tint #57352b → 渲染  8.6°
 *     S8_12 旧木柄      tint #52351f → 渲染 16.5°
 *     S8_13 缠光皮柄    tint #8b542f → 渲染 16.4°
 *   真胡桃木/真皮的色相在 **28–38°**；14–27° 配低明度就是**砖红/铁锈**，
 *   这正是用户看到的"奇怪的红色底"。其余 20 张红占比 = 0，不是问题。
 *   → 把这 4 张的色相抬到 30° 以上、饱和度压到 ≤0.55。
 *
 * ── 改动二：两处轻微校正（"稍微优化配色"）────────────────────────
 *   · S8_06 战术柄 / S8_15 模块军绿：实测渲染色相 114.6° / 114.7°，
 *     比 tint 的 95–97° 偏绿约 18°（程序化外观 kind 5 / 14 自身带绿）。
 *     → tint 往黄侧让 ~13°，抵消回橄榄军绿。
 *   · S8_21 共鸣神玉：饱和度 0.81（全部 24 张最高）→ 略压到 0.72，
 *     保留"神玉"的贵气但不刺眼。
 *
 * ⚠ 已知但**本轮未动**的问题：着色首行 `max(uHandleTint * 2.0, 0)` 会把
 *   >0.5 的通道削顶（legacy 24 张里 14 张削顶）。削顶会压平高饱和色的色相，
 *   但用户判定原项目观感更好，所以不整体重配 —— 留作后续单独议题。
 *
 * 优先级（见 core/recipe.js#deriveHandleMask）：
 *   **显式 `tint`（仅探针调试染色用） > 本表 > 传入的卡表值**
 *   （卡表值必须排在后面：`Game.previewVisual()` 会把候选卡的 write 当 overrides 传进来，
 *    若它赢就会「预览用旧配色、确认后用新配色」。）
 *
 * 回退：清空本表即回到原项目取值。
 */

/** 键 = handleMaterials 的材质 id（= cardWrites 里 handle.metalId） */
